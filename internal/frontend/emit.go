// emitModule turns the program bodies into ebpf dialect module text (① ops only — the Syntax of bpf-mlir's docs/reference/ebpf_ops.md).
func emitModule(subs []*Subprogram, progs []*Program, cbs []*TimerCallback, ucbs []*UrbCallback) []byte {
	var b strings.Builder
	b.WriteString("// Code generated by gobpf. DO NOT EDIT.\n")
	for _, cb := range cbs { // timer callbacks (top-level ebpf.timer.callback in the module)
		rt := cb.m.Value.mlir()
		fmt.Fprintf(&b, "ebpf.timer.callback @%s map @%s : %s {\n^bb0(%%v: !ebpf.borrowed<%s>):\n%s}%s\n\n", cb.Symbol, cb.m.Symbol, rt, rt, cb.body, locText(cb.Pos))
	}
	b.WriteString(emitUrbCallbacks(ucbs)) // top-level ebpf.user_ringbuf.callback in the module
	for _, s := range subs {
		var ps, args []string
		for i, t := range s.params {
			ty := t.carrier().mlir()
			if pp := s.ptrs[i]; pp != nil { // a borrowed map value argument
				ty = pp.mlirType()
			}
			if s.win != nil && s.win.idx == i { // a packet window argument
				ty = fmt.Sprintf("!ebpf.pkt_window<%d>", s.win.n)
			}
			name := fmt.Sprintf("%%a%d", i)
			if s.ctx != nil && i == 0 { // the program context (the block argument is %ctx — the same lowering as the program body)
				ty, name = fmt.Sprintf("!ebpf.ctx<%q>", s.ctx.Kind), "%ctx"
			}
			ps = append(ps, ty)
			args = append(args, fmt.Sprintf("%s: %s", name, ty))
		}
		linkage := "static"
		if s.global { // `//gobpf:global`
			linkage = "global"
		}
		fmt.Fprintf(&b, "ebpf.func @%s %q (%s) -> %s", s.Symbol, linkage, strings.Join(ps, ", "), s.result.carrier().mlir())
		if len(s.Maps) > 0 {
			var syms []string
			for _, m := range s.Maps {
				syms = append(syms, "@"+m.Symbol)
			}
			fmt.Fprintf(&b, " maps [%s]", strings.Join(syms, ", "))
		}
		b.WriteString(" {\n")
		for i, m := range s.Maps {
			args = append(args, fmt.Sprintf("%%m%d: %s", i, mapTypeOf(m)))
		}
		fmt.Fprintf(&b, "^bb0(%s):\n", strings.Join(args, ", "))
		b.WriteString(s.body)
		b.WriteString("}" + locText(s.Pos) + "\n\n")
	}
	for i, p := range progs {
		if i > 0 {
			b.WriteByte('\n')
		}
		fmt.Fprintf(&b, "ebpf.program @%s %q", p.Symbol, p.ProgramType)
		if isMultiKind(p.ProgramType) { // a list `attach ["f1", "f2"]`
			var qs []string
			for _, f := range strings.Fields(p.Attach) {
				qs = append(qs, fmt.Sprintf("%q", f))
			}
			fmt.Fprintf(&b, " attach [%s]", strings.Join(qs, ", "))
		} else if p.Attach != "" {
			fmt.Fprintf(&b, " attach %q", p.Attach) // the sched_cls direction
		}
		if hasArch(p.ProgramType) {
			fmt.Fprintf(&b, " arch %q", kprobeArch)
		}
		if len(p.Maps) > 0 {
			var syms []string
			for _, m := range p.Maps {
				syms = append(syms, "@"+m.Symbol)
			}
			fmt.Fprintf(&b, " maps [%s]", strings.Join(syms, ", "))
		}
		b.WriteString(" {\n")
		args := []string{fmt.Sprintf("%%ctx: !ebpf.ctx<%q>", p.ProgramType)}
		for i, m := range p.Maps {
			args = append(args, fmt.Sprintf("%%m%d: %s", i, mapTypeOf(m)))
		}
		fmt.Fprintf(&b, "^bb0(%s):\n", strings.Join(args, ", "))
		b.WriteString(p.body)
		b.WriteString("}" + locText(p.Pos) + "\n")
	}
	return []byte(b.String())
}

// --- schema (the shape of bpf-mlir's lib/Target/EBPF/Schema.cpp — 5 root keys; coverage and telemetry cannot be omitted) ---

type schemaInt struct {
	Kind       string `json:"kind"`
	Bits       int    `json:"bits"`
	Signed     bool   `json:"signed"`
	Endianness string `json:"endianness"`
	Alignment  int    `json:"alignment"`
}

type schemaMap struct {
	Symbol     string           `json:"symbol"`
	Kind       string           `json:"kind"`
	Key        any              `json:"key,omitempty"` // *schemaInt | *schemaArray | *schemaRecordRef
	Value      any              `json:"value,omitempty"`
	MaxEntries uint64           `json:"max_entries"`
	Flags      uint64           `json:"flags"`
	Record     string           `json:"record"`
	Slots      []schemaSlot     `json:"slots,omitempty"`      // prog_array slot declarations
	Inner      string           `json:"inner,omitempty"`      // the symbol of the inner template map of a map-in-map
	StructOps  *schemaStructOps `json:"struct_ops,omitempty"` // struct_ops type, name, members and programs
	Note       string           `json:"note"`
}

// schemaSlot is one prog_array slot (the index and the name of a program in the same ELF).
type schemaSlot struct {
	Index   uint64 `json:"index"`
	Program string `json:"program"`
}

type schemaProgram struct {
	Name         string          `json:"name"`
	Kind         string          `json:"kind"`
	AttachTarget any             `json:"attach_target"`   // a string; for multi probes an array of names
	Nargs        *int            `json:"nargs,omitempty"` // the fexit signature
	Ret          any             `json:"ret,omitempty"`   // *schemaInt; "void" for a void struct_ops member
	Maps         []string        `json:"maps"`
	Arch         string          `json:"arch,omitempty"`          // kprobe (bpf-mlir supports x86_64 only)
	Params       []schemaParam   `json:"params,omitempty"`        // kprobe argument types (KprobeArg — in order of n)
	BinarySHA256 string          `json:"binary_sha256,omitempty"` // the uprobe target binary
	Args         []any           `json:"args,omitempty"`          // tp_btf / fentry argument i (struct name, nullable object, integer type or null — a positional array)
	Fields       []schemaTPField `json:"fields,omitempty"`        // tracepoint event fields
	Semaphore    string          `json:"semaphore,omitempty"`     // the usdt point's semaphore ("required" / "none" — from the note)
	MaxPoints    int             `json:"max_points,omitempty"`    // the size of the usdt spec map (the number of points in the binary — from the note)
	Note         string          `json:"note"`
}

// schemaTPField is one of a tracepoint program's fields (name, byte offset from the record start, integer type).
type schemaTPField struct {
	Name   string     `json:"name"`
	Offset int64      `json:"offset"`
	Type   *schemaInt `json:"type"`
}

// hasArch reports whether kind carries arch in the schema and .mlir program (the kprobe family).
func hasArch(kind string) bool {
	return kind == "kprobe" || kind == "uprobe" || kind == "kretprobe" || kind == "uretprobe" || kind == "perf_event" || kind == "ksyscall" || kind == "usdt" || isMultiKind(kind) // perf_event: the ctx offsets assume the arch; ksyscall: pt_regs; usdt
}

// schemaParam is the type of the n-th kprobe argument (the program params of bpf-mlir's schema).
type schemaParam struct {
	N    int `json:"n"`
	Type any `json:"type"` // *schemaInt or user_str
}

type schemaDoc struct {
	Version  int `json:"version"`
	Coverage struct {
		Programs  string `json:"programs"`
		Maps      string `json:"maps"`
		Records   string `json:"records"`
		Telemetry string `json:"telemetry"`
	} `json:"coverage"`
	Core struct {
		Records     []schemaRecord     `json:"records"`
		Maps        []schemaMap        `json:"maps"`
		Programs    []schemaProgram    `json:"programs"`
		Globals     []schemaGlobal     `json:"globals,omitempty"`      // omitted when empty (existing schemas do not change)
		KernelTypes []schemaKernelType `json:"kernel_types,omitempty"` // tp_btf kernel local types (omitted when empty)
	} `json:"core"`
	Telemetry struct {
		Clocks     []struct{} `json:"clocks"`
		ValueMaps  []struct{} `json:"value_maps"`
		BoundsSets []struct{} `json:"bounds_sets"`
		Signals    []struct{} `json:"signals"`
	} `json:"telemetry"`
	Extensions struct{} `json:"extensions"`
}

func schemaIntOf(t IntType) *schemaInt {
	return &schemaInt{Kind: "int", Bits: t.Bits, Signed: t.Signed, Endianness: "little", Alignment: t.Bits / 8}
}

type schemaArray struct {
	Kind    string `json:"kind"`
	Count   uint64 `json:"count"`
	Element any    `json:"element"`
}

// schemaKind is a special type with no contents (spin_lock / timer).
type schemaKind struct {
	Kind string `json:"kind"`
}

type schemaRecordRef struct {
	Kind   string `json:"kind"`
	Symbol string `json:"symbol"`
}

type schemaField struct {
	Name   string `json:"name"`
	Offset uint64 `json:"offset"`
	Expose string `json:"expose"`
	Note   string `json:"note"`
	Type   any    `json:"type"`
}

// schemaRecord is a schema record (the keys of parseRecords in bpf-mlir's Schema.cpp). required_through is "" (all fields always present), min_size is size.
type schemaRecord struct {
	Symbol          string        `json:"symbol"`
	ID              int           `json:"id"`
	Size            uint64        `json:"size"`
	MinSize         uint64        `json:"min_size"`
	Alignment       uint64        `json:"alignment"`
	RequiredThrough string        `json:"required_through"`
	Note            string        `json:"note"`
	Fields          []schemaField `json:"fields"`
}

// schemaTypeOf turns a SharedABI into a schema type (integers, arrays; records become record_ref).
func schemaTypeOf(s SharedABI) any {
	switch s.Kind {
	case ABIInt:
		return schemaIntOf(*s.Int)
	case ABIArray:
		return &schemaArray{Kind: "array", Count: s.Array.Count, Element: schemaTypeOf(s.Array.Elem)}
	case ABIRecord:
		return &schemaRecordRef{Kind: "record_ref", Symbol: s.Record.Symbol}
	case ABISpinLock:
		return &schemaKind{Kind: "spin_lock"}
	case ABITimer:
		return &schemaKind{Kind: "timer"}
	case ABIStackBuildID:
		return &schemaKind{Kind: "stack_build_id"}
	}
	panic(fmt.Sprintf("gobpf: schemaTypeOf: unsupported shared ABI kind %d", s.Kind))
}

func buildSchema(maps []*BpfMap, records []*SharedABI, progs []*Program, globals []*GlobalVar, kernelTypes []*KernelType) ([]byte, error) {
	var s schemaDoc
	s.Version = 1
	// complete, because the frontend generates all programs, maps and records (with no records it is empty and complete).
	s.Coverage.Programs, s.Coverage.Maps, s.Coverage.Records, s.Coverage.Telemetry = "complete", "complete", "complete", "complete"
	s.Core.Records = []schemaRecord{}
	s.Core.Maps = []schemaMap{}
	s.Core.Programs = []schemaProgram{}
	for i, r := range sortedRecords(records) {
		sr := schemaRecord{Symbol: r.Record.Symbol, ID: i, Size: r.Size, MinSize: r.Size, Alignment: r.Align, Note: "Go type " + r.Record.GoType(), Fields: []schemaField{}}
		for _, f := range r.Record.Fields {
			sr.Fields = append(sr.Fields, schemaField{Name: f.Name, Offset: f.Offset, Expose: "int", Note: "Go field " + f.GoName, Type: schemaTypeOf(f.Type)})
		}
		s.Core.Records = append(s.Core.Records, sr)
	}
	s.Telemetry.Clocks, s.Telemetry.ValueMaps, s.Telemetry.BoundsSets, s.Telemetry.Signals = []struct{}{}, []struct{}{}, []struct{}{}, []struct{}{}
	for _, m := range maps {
		if m.Kind == "ringbuf" || m.Kind == "user_ringbuf" { // user_ringbuf names its sample record too
			// A ring buffer has no key / value and names its event record (bpf-mlir's Schema.cpp — record is required).
			s.Core.Maps = append(s.Core.Maps, schemaMap{Symbol: m.Symbol, Kind: m.Kind, MaxEntries: m.MaxEntries, Record: m.Value.Record.Symbol, Note: "Go var " + m.Symbol})
			continue
		}
		if so := m.StructOps; so != nil { // key u32, no value, the struct_ops type, name, members and programs (bpf-mlir's Schema.cpp)
			sso := &schemaStructOps{Type: so.Type, Name: so.Name, Ops: []schemaStructOp{}}
			for _, op := range so.Ops {
				sso.Ops = append(sso.Ops, schemaStructOp{Member: op.Member, Program: op.Program})
			}
			s.Core.Maps = append(s.Core.Maps, schemaMap{Symbol: m.Symbol, Kind: m.Kind, Key: schemaTypeOf(m.Key), MaxEntries: m.MaxEntries, StructOps: sso, Note: "Go var " + m.Symbol})
			continue
		}
		sm := schemaMap{
			Symbol: m.Symbol, Kind: m.Kind, Value: schemaTypeOf(m.Value),
			MaxEntries: m.MaxEntries, Flags: m.Flags, Note: "Go var " + m.Symbol, // no position (the schema is part of a hashed contract)
		}
		if !isKeylessKind(m.Kind) {
			sm.Key = schemaTypeOf(m.Key) // a keyless map's schema has only the value (bpf-mlir's Schema.cpp)
		}
		for _, sl := range m.Slots {
			sm.Slots = append(sm.Slots, schemaSlot{Index: sl.Index, Program: sl.Program})
		}
		if m.Event != nil {
			sm.Record = m.Event.Record.Symbol // the perf_event_array payload (bpf-mlir feature path F28)
		}
		if t := m.InnerTpl; t != nil { // the outer map's inner, and right after it the template map (not in the program maps or the ELF .maps)
			sm.Inner = t.Symbol
			s.Core.Maps = append(s.Core.Maps, sm)
			s.Core.Maps = append(s.Core.Maps, schemaMap{Symbol: t.Symbol, Kind: t.Kind, Key: schemaTypeOf(t.Key), Value: schemaTypeOf(t.Value),
				MaxEntries: t.MaxEntries, Flags: t.Flags, Note: "inner map template of Go var " + m.Symbol})
			continue
		}
		s.Core.Maps = append(s.Core.Maps, sm)
	}
	for _, p := range progs {
		var ms []string
		for _, m := range p.Maps {
			ms = append(ms, m.Symbol)
		}
		if ms == nil {
			ms = []string{}
		}
		// The xdp attach target is decided at runtime (gobpf.AttachXDP's ifindex) — not written to the schema.
		sp := schemaProgram{Name: p.Symbol, Kind: p.ProgramType, AttachTarget: p.Attach, Maps: ms, Note: "Go func " + p.Symbol}
		if isMultiKind(p.ProgramType) {
			sp.AttachTarget = strings.Fields(p.Attach) // a list
		}
		if (p.ProgramType == "fexit" || p.ProgramType == "fmod_ret") && p.Ret != nil { // fmod_ret too — retsig
			n := p.Nargs
			sp.Nargs, sp.Ret = &n, schemaIntOf(*p.Ret)
		}
		if p.ProgramType == "struct_ops" { // the member signature (the requirements' retsig — checked against the target BTF at load time)
			n := p.Nargs
			sp.Nargs, sp.Ret = &n, "void"
			if p.Ret != nil {
				sp.Ret = schemaIntOf(*p.Ret)
			}
		}
		if p.ProgramType == "ext" && p.Ret != nil { // the replaced function's signature (the requirements' extret / extarg — unsigned of the same width, see ext.go)
			n := p.Nargs
			sp.Nargs, sp.Ret, sp.Args = &n, schemaIntOf(IntType{Bits: p.Ret.Bits}), p.extSchemaArgs()
		}
		if p.ProgramType == "usdt" {
			sp.Semaphore, sp.MaxPoints = p.USDTSemaphore, p.USDTMaxPoints // from the note
		}
		if p.ProgramType == "kprobe" || p.ProgramType == "uprobe" || p.ProgramType == "ksyscall" || p.ProgramType == "kprobe_multi" || p.ProgramType == "uprobe_multi" || p.ProgramType == "usdt" { // ksyscall: params are the syscall arguments; kprobe_multi / uprobe_multi: the same for all functions; usdt: the point's arguments
			sp.Arch = kprobeArch
			for _, n := range p.allParamOrder() {
				if _, isStr := p.StrParams[n]; isStr {
					sp.Params = append(sp.Params, schemaParam{N: n, Type: map[string]string{"kind": "user_str"}})
				} else if _, isPtr := p.PtrParams[n]; isPtr {
					sp.Params = append(sp.Params, schemaParam{N: n, Type: map[string]string{"kind": "ptr"}}) // a kprobe pointer argument
				} else {
					sp.Params = append(sp.Params, schemaParam{N: n, Type: schemaIntOf(p.Params[n])})
				}
			}
			sp.BinarySHA256 = p.BinarySHA256 // uprobe (no path)
		}
		if isRetprobeKind(p.ProgramType) {
			sp.Arch, sp.BinarySHA256 = kprobeArch, p.BinarySHA256 // no params (return value only); also kretprobe_multi / uretprobe_multi
		}
		if p.ProgramType == "perf_event" {
			sp.Arch = kprobeArch // bpf_perf_event_data offsets depend on the arch's pt_regs (no params)
		}
		for _, f := range p.TPFields { // the tagged fields of the tracepoint event struct (ascending offset)
			sp.Fields = append(sp.Fields, schemaTPField{Name: f.Name, Offset: f.Offset, Type: schemaIntOf(f.Int)})
		}
		if p.ProgramType == "tp_btf" {
			sp.Args = p.argsSchema() // a positional array (null for arguments not read)
		} else if (p.ProgramType == "fentry" || isLSMKind(p.ProgramType) || p.ProgramType == "fmod_ret" || p.ProgramType == "struct_ops") && len(p.args) > 0 { // also lsm hook arguments, fmod_ret, and struct_ops (tcp_sock — the farg is sock)
			sp.Args = p.argsSchema() // FentryArg kernel structs (the requirements' farg rows)
		}
		s.Core.Programs = append(s.Core.Programs, sp)
	}
	s.Core.Globals = schemaGlobals(globals)
	for _, kt := range kernelTypes { // local types (declared in the order of first TPArg use)
		note := "builtin local type of the iter program's bpf_iter_meta (CO-RE)"
		if kt.Note != "" { // other builtin local types (netfilter's nf_hook_state / sk_buff)
			note = kt.Note
		}
		if kt.GoType != nil {
			note = "Go type " + kt.GoType.Obj().Name() + " (local type — CO-RE)"
		}
		sk := schemaKernelType{Name: kt.Name, Note: note, Fields: []schemaKField{}}
		for _, f := range kt.Fields {
			sk.Fields = append(sk.Fields, schemaKField{Name: f.Name, Type: f.schemaType()})
		}
		s.Core.KernelTypes = append(s.Core.KernelTypes, sk)
	}
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetIndent("", "  ")
	enc.SetEscapeHTML(false)
	if err := enc.Encode(&s); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

// --- domain graph (`gobpf --emit=domain-graph`) ---

type GraphNode struct {
	Func   string `json:"func"`
	Domain string `json:"domain"` // "ebpf" | "user"
	Root   bool   `json:"root,omitempty"`
	Kind   string `json:"kind,omitempty"`
	Pos    string `json:"pos"`
	// Membership is which roots reach the node ("user" / "bpf"). Domain is kept for compatibility ("ebpf" if it includes bpf).
	Membership []string `json:"membership"`
	// Requires is the capabilities an eBPF-side node needs (own ∪ callees).
	Requires []string `json:"requires,omitempty"`
}

type GraphEdge struct {
	From string `json:"from"`
	To   string `json:"to"`
	Kind string `json:"kind"` // "call" | "funcvalue"
	Via  string `json:"via,omitempty"`
	Pos  string `json:"pos"`
}

type GraphDiagnostic struct {
	Code    string   `json:"code"`
	Name    string   `json:"name"`
	Verdict string   `json:"verdict"`
	Pos     string   `json:"pos"`
	Path    []string `json:"path,omitempty"`
	Msg     string   `json:"msg"`
}

type DomainGraph struct {
	Package     string            `json:"package"`
	Nodes       []GraphNode       `json:"nodes"`
	Edges       []GraphEdge       `json:"edges"`
	Maps        []string          `json:"maps"`
	Diagnostics []GraphDiagnostic `json:"diagnostics"`
}

func posString(p token.Position) string { return fmt.Sprintf("%s:%d:%d", p.Filename, p.Line, p.Column) }

func (a *analyzer) buildGraph() {
	a.graph.Package = a.pkg.PkgPath
	byName := map[string]Membership{}
	for k, m := range a.reach {
		byName[k.Fn.Name()] |= m
	}
	for i := range a.graph.Nodes {
		a.graph.Nodes[i].Membership = byName[a.graph.Nodes[i].Func].List()
	}
	a.graph.Maps = []string{}
	for _, m := range a.maps {
		a.graph.Maps = append(a.graph.Maps, m.Symbol)
	}
	if a.graph.Nodes == nil {
		a.graph.Nodes = []GraphNode{}
	}
	if a.graph.Edges == nil {
		a.graph.Edges = []GraphEdge{}
	}
}

// GraphJSON renders the domain verdicts and diagnostics as JSON (deterministic — collection order and position order).
func (r *Result) GraphJSON() ([]byte, error) {
	g := r.Graph
	if g.Nodes == nil {
		g.Nodes = []GraphNode{}
	}
	if g.Edges == nil {
		g.Edges = []GraphEdge{}
	}
	if g.Maps == nil {
		g.Maps = []string{}
	}
	g.Package = r.PkgPath
	g.Diagnostics = []GraphDiagnostic{}
	for _, d := range r.Diagnostics {
		g.Diagnostics = append(g.Diagnostics, GraphDiagnostic{Code: string(d.Code), Name: codeNames[d.Code], Verdict: d.Verdict.String(), Pos: posString(d.Pos), Path: d.Path, Msg: d.Msg})
	}
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetIndent("", "  ")
	enc.SetEscapeHTML(false)
	if err := enc.Encode(g); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

// PosString returns the declaration position (relative to the package directory) — for the provenance comments of generated files.
func (m *BpfMap) PosString() string { return posString(m.Pos) }

// PosString returns the position of the declaration.
func (p *Program) PosString() string { return posString(p.Pos) }

// schemaKernelType is a local type in core.kernel_types (only the fields read, no offsets — CO-RE).
type schemaKernelType struct {
	Name   string         `json:"name"`
	Note   string         `json:"note"`
	Fields []schemaKField `json:"fields"`
}

type schemaKField struct {
	Name string `json:"name"`
	Type any    `json:"type"` // an integer, an 8-bit array, or a kptr
}
