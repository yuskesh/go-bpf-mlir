// Package layout independently checks ELF BTF against generated Go records.
// Both derive from the same schema through different implementations: C++/LLVM
// DWARF-to-BTF and Go bindgen/Decode. The kernel cannot observe record offset,
// size or decoding disagreements. Check compares BTF/schema/Go size, a one-to-
// one schema-tagged field/member mapping with offsets/sizes, and Decode output
// against bytes at BTF offsets. CheckDecode checks decoding only, for callers
// that independently establish record shapes first. This package is stdlib-only.
package layout

import (
	"bytes"
	"debug/elf"
	"encoding/binary"
	"fmt"
	"reflect"
	"sort"
	"strings"
)

// Decoder is the per-record Decode function generated by bindgen.
type Decoder interface{ Decode([]byte) error }

// Record supplies generated Go-side record metadata.
type Record struct {
	Symbol string         // Schema record symbol, also the BTF STRUCT name.
	Size   uintptr        // Schema size, as in the binding's Size constant.
	New    func() Decoder // Return a pointer to a zero record for reflection and Decode.
}

// Check compares ELF BTF with recs, returning all mismatches or nil.
func Check(elfBytes []byte, recs []Record) error {
	b, err := parseBTF(elfBytes)
	if err != nil {
		return err
	}
	var problems []string
	for _, r := range recs {
		problems = append(problems, checkRecord(b, r)...)
	}
	if len(problems) > 0 {
		return fmt.Errorf("BTF and Go bindings layouts differ:\n  %s", strings.Join(problems, "\n  "))
	}
	return nil
}

// CheckDecode decodes position-distinct bytes and compares schema-tagged field
// values to BTF member offsets. It does not establish size or one-to-one field
// shape/offset/type agreement: callers must first check that independently, e.g.
// with bindrt records. It still names missing BTF members, incompatible field
// sizes and Decode panics that prevent comparison.
func CheckDecode(elfBytes []byte, recs []Record) error {
	b, err := parseBTF(elfBytes)
	if err != nil {
		return err
	}
	var problems []string
	for _, r := range recs {
		id, ok := b.structs[r.Symbol]
		if !ok {
			problems = append(problems, fmt.Sprintf("record %s: struct %q is missing from BTF", r.Symbol, r.Symbol))
			continue
		}
		problems = append(problems, decodeProblems(b, b.types[id], r, true)...)
	}
	if len(problems) > 0 {
		return fmt.Errorf("Go bindings Decode does not read according to the BTF layout:\n  %s", strings.Join(problems, "\n  "))
	}
	return nil
}

// MapValue associates an ELF map symbol with a schema/BTF record name.
type MapValue struct {
	Map, Record string
	// Definition member to check: key or value; empty defaults to value.
	Member string
}

// CheckMapValues requires .maps VAR -> anonymous STRUCT member value (or key
// when requested) -> PTR -> STRUCT Record. A different record must fail even
// if its standalone layout has the same size.
func CheckMapValues(elfBytes []byte, mvs []MapValue) error {
	b, err := parseBTF(elfBytes)
	if err != nil {
		return err
	}
	var problems []string
	for _, mv := range mvs {
		id, ok := b.vars[mv.Map]
		if !ok {
			problems = append(problems, fmt.Sprintf("map %s: VAR is missing from BTF", mv.Map))
			continue
		}
		def := b.resolve(id)
		want := mv.Member
		if want == "" {
			want = "value"
		}
		var value *member
		for i := range def.members {
			if def.members[i].name == want {
				value = &def.members[i]
			}
		}
		if def.kind != kindStruct || value == nil {
			problems = append(problems, fmt.Sprintf("map %s: map definition has no %s member", mv.Map, want))
			continue
		}
		ptr := b.resolve(value.typeID)
		if ptr.kind != kindPtr {
			problems = append(problems, fmt.Sprintf("map %s: member %s is not a pointer", mv.Map, want))
			continue
		}
		target := b.resolve(ptr.typeID)
		if target.kind != kindStruct || target.name != mv.Record {
			problems = append(problems, fmt.Sprintf("map %s: %s points to struct %q (bindings: record %q)", mv.Map, want, target.name, mv.Record))
			continue
		}
		// Require the actual same STRUCT identity that Check validated, not only
		// a matching name.
		if id, ok := b.structs[mv.Record]; !ok || b.types[id] != target {
			problems = append(problems, fmt.Sprintf("map %s: %s struct %q has a different type from layout-checked struct %q", mv.Map, want, target.name, mv.Record))
		}
	}
	if len(problems) > 0 {
		return fmt.Errorf("BTF map values and Go bindings records differ:\n  %s", strings.Join(problems, "\n  "))
	}
	return nil
}

func checkRecord(b *btf, r Record) []string {
	var out []string
	id, ok := b.structs[r.Symbol]
	if !ok {
		return []string{fmt.Sprintf("record %s: struct %q is missing from BTF", r.Symbol, r.Symbol)}
	}
	st := b.types[id]
	if st.bitfield {
		out = append(out, fmt.Sprintf("record %s: BTF struct has a bitfield (schema records have integer fields only)", r.Symbol))
	}
	rt := reflect.TypeOf(r.New()).Elem()
	if uintptr(st.size) != r.Size || rt.Size() != r.Size {
		out = append(out, fmt.Sprintf("record %s: sizes differ (BTF %d / schema %d / Go %d)", r.Symbol, st.size, r.Size, rt.Size()))
	}
	out = append(out, compareFields(b, st, rt, r.Symbol)...)

	return append(out, decodeProblems(b, st, r, false)...)
}

// decodeProblems uses position-distinct bytes to check Decode against BTF
// offsets. decodeOnly must also diagnose panics, missing members and size
// differences because no shape check preceded it.
func decodeProblems(b *btf, st *btfType, r Record, decodeOnly bool) (out []string) {
	v := r.New()
	rv := reflect.ValueOf(v).Elem()
	buf := make([]byte, st.size)
	for i := range buf {
		buf[i] = byte(i*7 + 1)
	}
	if decodeOnly {
		defer func() {
			if p := recover(); p != nil {
				out = append(out, fmt.Sprintf("record %s: Decode panicked (BTF struct size: %d bytes): %v", r.Symbol, st.size, p))
			}
		}()
	}
	if err := v.Decode(buf); err != nil {
		return append(out, fmt.Sprintf("record %s: Decode failed: %v", r.Symbol, err))
	}
	return append(out, compareValues(b, st, rv, buf, r.Symbol, decodeOnly)...)
}

// OpaqueSizes lists special kernel structs hidden as binding holes. Developer
// tests check sizes against UAPI abi/uapi.tsv uapistruct entries.
var OpaqueSizes = map[string]uint32{"bpf_spin_lock": 4, "bpf_timer": 16}

// KptrOpaque/KptrSize describe referenced kptr holes: PTR -> TYPE_TAG kptr ->
// STRUCT, an eight-byte pointer rather than a UAPI struct in OpaqueSizes.
const (
	KptrOpaque        = "kptr"
	KptrSize   uint32 = 8
)

// kptrTarget extracts T from referenced kptr PTR -> TYPE_TAG kptr -> STRUCT T.
func (b *btf) kptrTarget(id uint32) (string, bool) {
	p := b.resolve(id)
	if p.kind != kindPtr || int(p.typeID) >= len(b.types) {
		return "", false
	}
	tt := b.types[p.typeID]
	if tt.kind != kindTypeTag || tt.name != "kptr" {
		return "", false
	}
	s := b.resolve(tt.typeID)
	if s.kind != kindStruct {
		return "", false
	}
	return s.name, true
}

// arrayHasStruct tests the innermost array element type.
func arrayHasStruct(b *btf, t *btfType) bool {
	for t.kind == kindArray {
		t = b.resolve(t.typeID)
	}
	return t.kind == kindStruct
}

// compareArrayValues checks each element recursively.
func compareArrayValues(b *btf, t *btfType, fv reflect.Value, want []byte, where string, decodeOnly bool) []string {
	elem := b.resolve(t.typeID)
	esz := int(b.sizeOf(t.typeID))
	var out []string
	for i := 0; i < fv.Len() && (i+1)*esz <= len(want); i++ {
		w := want[i*esz : (i+1)*esz]
		at := fmt.Sprintf("%s[%d]", where, i)
		switch elem.kind {
		case kindStruct:
			out = append(out, compareValues(b, elem, fv.Index(i), w, at, decodeOnly)...)
		case kindArray:
			out = append(out, compareArrayValues(b, elem, fv.Index(i), w, at, decodeOnly)...)
		}
	}
	return out
}

// compareFields requires a one-to-one Go-field/BTF-member mapping. Opaque
// structs instead require one blank field with exactly matching offset/size
// and schema/opaque tags; BTF size must also match OpaqueSizes.
func compareFields(b *btf, st *btfType, rt reflect.Type, where string) []string {
	var out []string
	goFields := map[string]reflect.StructField{}
	opaque := map[string][]reflect.StructField{} // Schema name to blank field with opaque tag.
	for i := 0; i < rt.NumField(); i++ {
		f := rt.Field(i)
		if on, ok := f.Tag.Lookup("opaque"); ok {
			if f.Name != "_" {
				out = append(out, fmt.Sprintf("%s.%s: field with opaque tag (%s) must be blank (_) (inaccessible through the public Go struct)", where, f.Name, on))
				continue
			}
			opaque[f.Tag.Get("schema")] = append(opaque[f.Tag.Get("schema")], f)
			continue
		}
		if strings.HasPrefix(f.Name, "_") {
			continue // Holes declared by the schema.
		}
		name, ok := f.Tag.Lookup("schema")
		if !ok {
			out = append(out, fmt.Sprintf("%s.%s: Go field has no schema tag", where, f.Name))
			continue
		}
		goFields[name] = f
	}
	for _, m := range st.members {
		// Referenced kptrs also require one opaque _ [8]byte hole. Userspace
		// updates release held references through kernel destructors; arbitrary
		// pointer values are not accepted by the kernel.
		if _, isKptr := b.kptrTarget(m.typeID); isKptr {
			out = append(out, checkOpaque(opaque[m.name], m, &btfType{name: KptrOpaque, size: KptrSize}, KptrSize, where)...)
			delete(opaque, m.name)
			if _, named := goFields[m.name]; named {
				out = append(out, fmt.Sprintf("%s.%s: kptr is an inaccessible hole in the Go binding — it must not be a named field", where, m.name))
				delete(goFields, m.name)
			}
			continue
		}
		if mt := b.resolve(m.typeID); mt.kind == kindStruct {
			if usize, special := OpaqueSizes[mt.name]; special {
				out = append(out, checkOpaque(opaque[m.name], m, mt, usize, where)...)
				delete(opaque, m.name)
				if _, named := goFields[m.name]; named {
					out = append(out, fmt.Sprintf("%s.%s: %s is an inaccessible hole in the Go binding — it must not be a named field", where, m.name, mt.name))
					delete(goFields, m.name)
				}
				continue
			}
		}
		f, ok := goFields[m.name]
		if !ok {
			out = append(out, fmt.Sprintf("%s.%s: no Go field corresponds to this BTF member", where, m.name))
			continue
		}
		delete(goFields, m.name)
		msize := b.sizeOf(m.typeID)
		if f.Offset != uintptr(m.offset) {
			out = append(out, fmt.Sprintf("%s.%s: offsets differ (BTF %d / Go %d)", where, m.name, m.offset, f.Offset))
		}
		if f.Type.Size() != uintptr(msize) {
			out = append(out, fmt.Sprintf("%s.%s: sizes differ (BTF %d / Go %d)", where, m.name, msize, f.Type.Size()))
		}
		// Compare shape, not only bytes: u16[3] must differ from u8[6], and
		// differently named nested structs must not pass on matching layout alone.
		out = append(out, compareShape(b, b.resolve(m.typeID), f, where+"."+m.name)...)
	}
	// Sort remaining schema fields/holes so map iteration cannot randomize
	// diagnostic order.
	for _, name := range sortedKeys(goFields) {
		out = append(out, fmt.Sprintf("%s.%s: no BTF member corresponds to this Go field", where, name))
	}
	for _, name := range sortedKeys(opaque) {
		out = append(out, fmt.Sprintf("%s.%s: no special BTF member (bpf_spin_lock / bpf_timer) corresponds to the opaque holes (%d)", where, name, len(opaque[name])))
	}
	return out
}

// sortedKeys provides deterministic diagnostic ordering.
func sortedKeys[V any](m map[string]V) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

// checkOpaque requires exactly one blank field matching member m's offset,
// size and opaque tag name.
func checkOpaque(fs []reflect.StructField, m member, mt *btfType, usize uint32, where string) []string {
	at := where + "." + m.name
	if mt.size != usize {
		return []string{fmt.Sprintf("%s: BTF struct %s size %d differs from UAPI table size %d", at, mt.name, mt.size, usize)}
	}
	if len(fs) != 1 {
		return []string{fmt.Sprintf("%s: %s corresponds to %d opaque blank fields (one `_ [%d]byte` is required)", at, mt.name, len(fs), usize)}
	}
	f := fs[0]
	var out []string
	if on := f.Tag.Get("opaque"); on != mt.name {
		out = append(out, fmt.Sprintf("%s: opaque tag %q differs from BTF struct name %q", at, on, mt.name))
	}
	if f.Offset != uintptr(m.offset) {
		out = append(out, fmt.Sprintf("%s: offsets differ (BTF %d / Go hole %d)", at, m.offset, f.Offset))
	}
	if f.Type.Kind() != reflect.Array || f.Type.Elem().Kind() != reflect.Uint8 || f.Type.Size() != uintptr(usize) {
		out = append(out, fmt.Sprintf("%s: hole must be [%d]byte (Go: %s)", at, usize, f.Type))
	}
	return out
}

// compareArrayShape recursively compares BTF and Go arrays. rec names the
// innermost record when the element is a struct.
func compareArrayShape(b *btf, t *btfType, gt reflect.Type, rec, where string) []string {
	if gt.Kind() != reflect.Array {
		return []string{fmt.Sprintf("%s: type kinds differ (BTF: array / Go: %s)", where, gt)}
	}
	if uint32(gt.Len()) != t.nelems {
		return []string{fmt.Sprintf("%s: array element counts differ (BTF %d / Go %d)", where, t.nelems, gt.Len())}
	}
	elem := b.resolve(t.typeID)
	ge := gt.Elem()
	switch elem.kind {
	case kindInt:
		if !isIntKind(ge.Kind()) || uint32(ge.Size()) != elem.size {
			return []string{fmt.Sprintf("%s: array elements differ (BTF: %d-byte integer / Go: %s)", where, elem.size, ge)}
		}
		if elem.signed != isSignedKind(ge.Kind()) {
			return []string{fmt.Sprintf("%s: array element signedness differs (BTF signed=%v / Go %s)", where, elem.signed, ge)}
		}
		return nil
	case kindArray:
		return compareArrayShape(b, elem, ge, rec, where+"[]")
	case kindStruct:
		if ge.Kind() != reflect.Struct {
			return []string{fmt.Sprintf("%s: array element type kinds differ (BTF: struct %q / Go: %s)", where, elem.name, ge)}
		}
		if rec != elem.name {
			return []string{fmt.Sprintf("%s: array element points to struct %q (bindings: record %q)", where, elem.name, rec)}
		}
		return compareFields(b, elem, ge, where+"[]")
	}
	return []string{fmt.Sprintf("%s: unsupported BTF array element type (kind %d)", where, elem.kind)}
}

func isSignedKind(k reflect.Kind) bool {
	switch k {
	case reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64:
		return true
	}
	return false
}

// isIntKind recognizes Go integer kinds.
func isIntKind(k reflect.Kind) bool {
	switch k {
	case reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64:
		return true
	}
	return false
}

// compareShape checks BTF INT against Go integers, ARRAY against matching
// element counts/widths and STRUCT against a Go struct with a matching record
// tag, then recursively checks its contents.
func compareShape(b *btf, t *btfType, f reflect.StructField, where string) []string {
	switch t.kind {
	case kindInt:
		if !isIntKind(f.Type.Kind()) {
			return []string{fmt.Sprintf("%s: type kinds differ (BTF: integer / Go: %s)", where, f.Type)}
		}
	case kindArray:
		// Recurse through element width, array dimensions/counts and record
		// element names (the field's record tag).
		return compareArrayShape(b, t, f.Type, f.Tag.Get("record"), where)
	case kindStruct:
		if f.Type.Kind() != reflect.Struct {
			return []string{fmt.Sprintf("%s: type kinds differ (BTF: struct %q / Go: %s)", where, t.name, f.Type)}
		}
		if rec := f.Tag.Get("record"); rec != t.name {
			return []string{fmt.Sprintf("%s: points to nested struct %q (bindings: record %q)", where, t.name, rec)}
		}
		return compareFields(b, t, f.Type, where)
	default:
		// Reject all other field kinds by default. An eight-byte PTR can match
		// uint64 in size and decoded bytes, so only shape validation catches it.
		return []string{fmt.Sprintf("%s: BTF type (kind %d) is unsupported as a record field (only integers, integer arrays, and nested structs)", where, t.kind)}
	}
	return nil
}

// compareValues compares decoded values with bytes at BTF offsets.
func compareValues(b *btf, st *btfType, rv reflect.Value, buf []byte, where string, decodeOnly bool) []string {
	var out []string
	rt := rv.Type()
	for i := 0; i < rt.NumField(); i++ {
		f := rt.Field(i)
		name := f.Tag.Get("schema")
		if name == "" {
			continue
		}
		if _, ok := f.Tag.Lookup("opaque"); ok {
			continue // Opaque holes are not decoded; compareFields already checks their layout.
		}
		var m *member
		for j := range st.members {
			if st.members[j].name == name {
				m = &st.members[j]
			}
		}
		if m == nil {
			if decodeOnly {
				out = append(out, fmt.Sprintf("%s.%s: cannot check Decode — BTF struct has no member %q", where, name, name))
			}
			continue // Check's compareFields already reported this.
		}
		size := b.sizeOf(m.typeID)
		if int(m.offset+size) > len(buf) {
			out = append(out, fmt.Sprintf("%s.%s: BTF member extends outside the struct", where, name))
			continue
		}
		want := buf[m.offset : m.offset+size]
		fv := rv.Field(i)
		if inner := b.resolve(m.typeID); inner.kind == kindStruct && fv.Kind() == reflect.Struct {
			out = append(out, compareValues(b, inner, fv, want, where+"."+name, decodeOnly)...)
			continue
		}
		// Recurse per struct element: encoding a struct hole would produce zero
			// and incorrectly disagree with the input bytes.
		if inner := b.resolve(m.typeID); inner.kind == kindArray && fv.Kind() == reflect.Array && arrayHasStruct(b, inner) {
			out = append(out, compareArrayValues(b, inner, fv, want, where+"."+name, decodeOnly)...)
			continue
		}
		got, err := encode(fv)
		if err != nil {
			out = append(out, fmt.Sprintf("%s.%s: %v", where, name, err))
			continue
		}
		if decodeOnly && len(got) != len(want) {
			out = append(out, fmt.Sprintf("%s.%s: cannot check Decode — Go field is %d bytes, BTF member is %d bytes", where, name, len(got), len(want)))
			continue
		}
		if !bytes.Equal(got, want) {
			out = append(out, fmt.Sprintf("%s.%s: Decode did not read bytes at BTF offset %d (read value %x / bytes at that offset %x)",
				where, name, m.offset, got, want))
		}
	}
	return out
}

// encode returns little-endian bytes for decoded integers/integer arrays.
func encode(v reflect.Value) ([]byte, error) {
	var buf bytes.Buffer
	switch v.Kind() {
	case reflect.Array:
		for i := 0; i < v.Len(); i++ {
			b, err := encode(v.Index(i))
			if err != nil {
				return nil, err
			}
			buf.Write(b)
		}
		return buf.Bytes(), nil
	case reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64:
		if err := binary.Write(&buf, binary.LittleEndian, v.Interface()); err != nil {
			return nil, err
		}
		return buf.Bytes(), nil
	}
	return nil, fmt.Errorf("cannot compare type %s", v.Type())
}

// Minimal BTF reader for record layout checks.

const (
	kindInt       = 1
	kindPtr       = 2
	kindArray     = 3
	kindStruct    = 4
	kindUnion     = 5
	kindEnum      = 6
	kindTypedef   = 8
	kindVolatile  = 9
	kindConst     = 10
	kindRestrict  = 11
	kindFuncProto = 13
	kindVar       = 14
	kindDatasec   = 15
	kindDeclTag   = 17
	kindTypeTag   = 18
	kindEnum64    = 19
)

type member struct {
	name   string
	typeID uint32
	offset uint32 // Bytes; bitfields are unsupported.
}

type btfType struct {
	kind     uint32
	name     string
	signed   bool         // INT SIGNED encoding flag.
	secinfo  []varSecinfo // DATASEC var_secinfo.
	size     uint32       // INT / STRUCT / UNION / ENUM / DATASEC
	typeID   uint32       // PTR/TYPEDEF/qualifier targets and ARRAY elements.
	nelems   uint32       // ARRAY
	members  []member
	bitfield bool
}

// varSecinfo describes a DATASEC VAR type ID, section offset and size.
type varSecinfo struct {
	typeID, offset, size uint32
	pos                  uint32 // Byte position of the offset field in .BTF, compared with relocation r_offset.
}

type btf struct {
	types   []*btfType // Type ID to type; zero means void.
	structs map[string]uint32
	vars    map[string]uint32 // VAR name to type; map definitions are .maps VARs.
}

func parseBTF(elfBytes []byte) (*btf, error) {
	f, err := elf.NewFile(bytes.NewReader(elfBytes))
	if err != nil {
		return nil, err
	}
	sec := f.Section(".BTF")
	if sec == nil {
		return nil, fmt.Errorf("the ELF has no .BTF section")
	}
	raw, err := sec.Data()
	if err != nil {
		return nil, err
	}
	le := binary.LittleEndian
	if len(raw) < 24 || le.Uint16(raw) != 0xeb9f {
		return nil, fmt.Errorf("the .BTF header cannot be read")
	}
	hdrLen := le.Uint32(raw[4:])
	typeOff, typeLen := le.Uint32(raw[8:]), le.Uint32(raw[12:])
	strOff, strLen := le.Uint32(raw[16:]), le.Uint32(raw[20:])
	// Check ranges in uint64 to reject uint32 addition overflow and out-of-section
	// data. Require a NUL-terminated string table. Keep error text stable: it
	// feeds maps.json format problems and is copied byte-for-byte by the C loader.
	n := uint64(len(raw))
	if uint64(hdrLen) < 24 || uint64(hdrLen) > n ||
		uint64(hdrLen)+uint64(typeOff)+uint64(typeLen) > n || uint64(hdrLen)+uint64(strOff)+uint64(strLen) > n {
		return nil, fmt.Errorf("the .BTF is corrupt: the header (length %d, types %d+%d, strings %d+%d) is outside the %d-byte section", hdrLen, typeOff, typeLen, strOff, strLen, n)
	}
	strs := raw[hdrLen+strOff : hdrLen+strOff+strLen]
	if len(strs) > 0 && strs[len(strs)-1] != 0 {
		return nil, fmt.Errorf("the .BTF is corrupt: the string table does not end with NUL")
	}
	str := func(off uint32) string {
		if int(off) >= len(strs) {
			return ""
		}
		end := bytes.IndexByte(strs[off:], 0)
		return string(strs[off : int(off)+end])
	}
	b := &btf{types: []*btfType{{}}, structs: map[string]uint32{}, vars: map[string]uint32{}}
	p, end := hdrLen+typeOff, hdrLen+typeOff+typeLen
	if (end-p)%4 != 0 {
		return nil, fmt.Errorf("the .BTF is corrupt: the type section length %d is not a multiple of 4", end-p)
	}
	for p < end {
		if uint64(p)+12 > uint64(end) {
			return nil, fmt.Errorf("the .BTF is corrupt: a type record ends inside the type section (offset %d)", p-hdrLen-typeOff)
		}
		// Validate kind/vlen-dependent payload size before reading it.
		pinfo := le.Uint32(raw[p+4:])
		if need := uint64(p) + 12 + uint64(btfRecordTail((pinfo>>24)&0x1f, pinfo&0xffff)); need > uint64(end) {
			return nil, fmt.Errorf("the .BTF is corrupt: a type record (kind %d, vlen %d) runs past the type section (offset %d)", (pinfo>>24)&0x1f, pinfo&0xffff, p-hdrLen-typeOff)
		}
		info := le.Uint32(raw[p+4:])
		t := &btfType{kind: (info >> 24) & 0x1f, name: str(le.Uint32(raw[p:]))}
		vlen, kflag := info&0xffff, info>>31 == 1
		sizeOrType := le.Uint32(raw[p+8:])
		p += 12
		switch t.kind {
		case kindInt, kindVar, kindDeclTag:
			t.size = sizeOrType
			if t.kind == kindVar {
				t.typeID = sizeOrType
			}
			if t.kind == kindInt {
				t.signed = (le.Uint32(raw[p:])>>24)&1 == 1 // BTF_INT_SIGNED
			}
			p += 4
		case kindArray:
			t.typeID, t.nelems = le.Uint32(raw[p:]), le.Uint32(raw[p+8:])
			p += 12
		case kindStruct, kindUnion:
			t.size = sizeOrType
			for i := uint32(0); i < vlen; i++ {
				m := raw[p+12*i:]
				off := le.Uint32(m[8:])
				if kflag {
					if off>>24 != 0 {
						t.bitfield = true
					}
					off &= 0xffffff
				}
				t.members = append(t.members, member{str(le.Uint32(m)), le.Uint32(m[4:]), off / 8})
			}
			p += 12 * vlen
		case kindEnum:
			t.size = sizeOrType
			p += 8 * vlen
		case kindEnum64:
			t.size = sizeOrType
			p += 12 * vlen
		case kindDatasec:
			t.size = sizeOrType
			for i := uint32(0); i < vlen; i++ {
				m := raw[p+12*i:]
				t.secinfo = append(t.secinfo, varSecinfo{le.Uint32(m), le.Uint32(m[4:]), le.Uint32(m[8:]), p + 12*i + 4})
			}
			p += 12 * vlen
		case kindFuncProto:
			p += 8 * vlen
		case kindPtr, kindTypedef, kindVolatile, kindConst, kindRestrict, kindTypeTag, 7, 12, 16:
			t.typeID = sizeOrType
			if t.kind == 16 { // FLOAT
				t.size = sizeOrType
			}
		default:
			return nil, fmt.Errorf("the .BTF has a type of kind %d that cannot be read", t.kind)
		}
		b.types = append(b.types, t)
		if t.kind == kindStruct && t.name != "" {
			// Duplicate STRUCT names can make name lookup validate a different type
			// than the map actually points to. Treat ambiguity as an error rather
			// than allowing the last type to overwrite the first.
			if _, dup := b.structs[t.name]; dup {
				return nil, fmt.Errorf("the .BTF has two structs named %q — the layout cannot be checked by name", t.name)
			}
			b.structs[t.name] = uint32(len(b.types) - 1)
		}
		if t.kind == kindVar {
			b.vars[t.name] = t.typeID
		}
	}
	return b, nil
}

// btfRecordTail computes the payload following the 12-byte type header from
// kind/vlen. Unknown kinds return zero and are rejected by parseBTF.
func btfRecordTail(kind, vlen uint32) uint32 {
	switch kind {
	case kindInt, kindVar, kindDeclTag:
		return 4
	case kindArray:
		return 12
	case kindStruct, kindUnion, kindEnum64, kindDatasec:
		return 12 * vlen
	case kindEnum, kindFuncProto:
		return 8 * vlen
	}
	return 0
}

// Global describes schema core.globals; Section is the ELF .rodata/.bss name.
type Global struct {
	Name, Section string
	Size          uint32
	Signed        bool
}

// CheckGlobals independently compares schema, ELF symbols and BTF, returning
// all mismatches. ELF symbol st_value/st_size/section owns byte positions;
// independently check DATASEC var_secinfo because cilium can overwrite offsets
// from ELF when DATASEC size is zero, hiding a BTF mismatch. Require a GLOBAL
// OBJECT symbol with matching section/size; matching DATASEC VAR offset/size;
// an INT VAR type with matching width/sign; and DATASEC size zero or actual
// section size. Relocatable .o offsets add R_BPF_64_ABS32/R_BPF_64_NODYLD32
// symbol values to raw offsets; linked ELF without relocations uses raw offsets.
func CheckGlobals(elfBytes []byte, gs []Global) error {
	f, err := elf.NewFile(bytes.NewReader(elfBytes))
	if err != nil {
		return err
	}
	syms, err := f.Symbols()
	if err != nil {
		return fmt.Errorf("the ELF symbol table cannot be read: %w", err)
	}
	b, err := parseBTF(elfBytes)
	if err != nil {
		return err
	}
	rels, err := btfRelocs(f)
	if err != nil {
		return err
	}
	var problems []string
	for _, g := range gs {
		problems = append(problems, checkGlobal(f, syms, b, rels, g)...)
	}
	if len(problems) > 0 {
		return fmt.Errorf("the ELF symbols, the BTF DATASEC and the declared globals differ:\n  %s", strings.Join(problems, "\n  "))
	}
	return nil
}

// GlobalProblems returns one global's mismatches using CheckGlobals rules, or
// an error when ELF/BTF cannot be read. Keep text stable for maps.json and the
// C loader's byte-for-byte copy.
func GlobalProblems(elfBytes []byte, g Global) ([]string, error) {
	f, err := elf.NewFile(bytes.NewReader(elfBytes))
	if err != nil {
		return nil, err
	}
	syms, err := f.Symbols()
	if err != nil {
		return nil, fmt.Errorf("the ELF symbol table cannot be read: %w", err)
	}
	b, err := parseBTF(elfBytes)
	if err != nil {
		return nil, err
	}
	rels, err := btfRelocs(f)
	if err != nil {
		return nil, err
	}
	return checkGlobal(f, syms, b, rels, g), nil
}

// GlobalSymbols maps .rodata/.bss GLOBAL OBJECT names to sections for checking
// undeclared globals.
func GlobalSymbols(elfBytes []byte) (map[string]string, error) {
	f, err := elf.NewFile(bytes.NewReader(elfBytes))
	if err != nil {
		return nil, err
	}
	syms, err := f.Symbols()
	if err != nil {
		return nil, fmt.Errorf("the ELF symbol table cannot be read: %w", err)
	}
	out := map[string]string{}
	for _, sy := range syms {
		if elf.ST_TYPE(sy.Info) != elf.STT_OBJECT || elf.ST_BIND(sy.Info) != elf.STB_GLOBAL || int(sy.Section) >= len(f.Sections) {
			continue
		}
		if n := f.Sections[sy.Section].Name; n == ".rodata" || n == ".bss" {
			out[sy.Name] = n
		}
	}
	return out, nil
}

// GlobalOffset returns the ELF-symbol section offset, independently compared
// by bindings against the loader's VariableSpec.
func GlobalOffset(elfBytes []byte, name string) (uint64, error) {
	f, err := elf.NewFile(bytes.NewReader(elfBytes))
	if err != nil {
		return 0, err
	}
	syms, err := f.Symbols()
	if err != nil {
		return 0, err
	}
	for _, s := range syms {
		if s.Name == name && elf.ST_TYPE(s.Info) == elf.STT_OBJECT {
			return s.Value, nil
		}
	}
	return 0, fmt.Errorf("global %s: symbol is missing from the ELF", name)
}

// btfReloc describes one .rel.BTF relocation.
type btfReloc struct {
	sym   uint32 // Symbol table index; zero is null, while f.Symbols starts at one.
	rtype uint32
}

// R_BPF_64_ABS32 or R_BPF_64_NODYLD32 from LLVM ELFRelocs/BPF.def.
const (
	rBPF64Abs32    = 3
	rBPF64NoDyld32 = 4
)

// btfRelocs maps r_offset to .BTF SHT_REL relocations; empty if absent.
func btfRelocs(f *elf.File) (map[uint32]btfReloc, error) {
	out := map[uint32]btfReloc{}
	btfSec := f.Section(".BTF")
	for _, s := range f.Sections {
		if s.Type != elf.SHT_REL || btfSec == nil || int(s.Info) >= len(f.Sections) || f.Sections[s.Info] != btfSec {
			continue
		}
		if f.Class != elf.ELFCLASS64 {
			return nil, fmt.Errorf("%s: not ELF64", s.Name)
		}
		data, err := s.Data()
		if err != nil {
			return nil, fmt.Errorf("cannot read %s: %w", s.Name, err)
		}
		for i := 0; i+16 <= len(data); i += 16 {
			off, info := f.ByteOrder.Uint64(data[i:]), f.ByteOrder.Uint64(data[i+8:])
			out[uint32(off)] = btfReloc{sym: uint32(info >> 32), rtype: uint32(info)}
		}
	}
	return out, nil
}

func checkGlobal(f *elf.File, syms []elf.Symbol, b *btf, rels map[uint32]btfReloc, g Global) []string {
	var sym *elf.Symbol
	for i := range syms {
		if syms[i].Name == g.Name && elf.ST_TYPE(syms[i].Info) == elf.STT_OBJECT {
			if sym != nil {
				return []string{fmt.Sprintf("global %s: the ELF has two symbols of that name", g.Name)}
			}
			sym = &syms[i]
		}
	}
	if sym == nil {
		return []string{fmt.Sprintf("global %s: the ELF has no OBJECT symbol of that name", g.Name)}
	}
	var problems []string
	if elf.ST_BIND(sym.Info) != elf.STB_GLOBAL {
		problems = append(problems, fmt.Sprintf("global %s: the symbol binding is %v (not GLOBAL)", g.Name, elf.ST_BIND(sym.Info)))
	}
	var sec *elf.Section
	if int(sym.Section) < len(f.Sections) {
		sec = f.Sections[sym.Section]
	}
	if sec == nil || sec.Name != g.Section {
		name := "?"
		if sec != nil {
			name = sec.Name
		}
		problems = append(problems, fmt.Sprintf("global %s: the symbol is in section %s (declared %s)", g.Name, name, g.Section))
	}
	if sym.Size != uint64(g.Size) {
		problems = append(problems, fmt.Sprintf("global %s: the symbol size is %d (declared %d)", g.Name, sym.Size, g.Size))
	}
	// BTF DATASEC and VAR evidence.
	var ds *btfType
	for _, t := range b.types {
		if t.kind == kindDatasec && t.name == g.Section {
			if ds != nil {
				return append(problems, fmt.Sprintf("global %s: the BTF has two DATASECs %s", g.Name, g.Section))
			}
			ds = t
		}
	}
	if ds == nil {
		return append(problems, fmt.Sprintf("global %s: the BTF has no DATASEC %s", g.Name, g.Section))
	}
	if sec != nil && ds.size != 0 && uint64(ds.size) != sec.Size {
		problems = append(problems, fmt.Sprintf("global %s: DATASEC %s has size %d (neither 0 nor the ELF section size %d)", g.Name, g.Section, ds.size, sec.Size))
	}
	var vsi *varSecinfo
	for i := range ds.secinfo {
		if int(ds.secinfo[i].typeID) < len(b.types) {
			if v := b.types[ds.secinfo[i].typeID]; v.kind == kindVar && v.name == g.Name {
				vsi = &ds.secinfo[i]
			}
		}
	}
	if vsi == nil {
		return append(problems, fmt.Sprintf("global %s: DATASEC %s has no VAR %s", g.Name, g.Section, g.Name))
	}
	off := uint64(vsi.offset)
	if r, ok := rels[vsi.pos]; ok { // Relocatable .o: add the relocation symbol's value.
		switch {
		case r.rtype != rBPF64Abs32 && r.rtype != rBPF64NoDyld32:
			problems = append(problems, fmt.Sprintf("global %s: the DATASEC offset relocation has type %d (not R_BPF_64_ABS32 / R_BPF_64_NODYLD32)", g.Name, r.rtype))
		case r.sym == 0 || int(r.sym) > len(syms) || syms[r.sym-1].Name != g.Name:
			name := "?"
			if r.sym != 0 && int(r.sym) <= len(syms) {
				name = syms[r.sym-1].Name
			}
			problems = append(problems, fmt.Sprintf("global %s: the DATASEC offset relocation refers to symbol %s", g.Name, name))
		default:
			off += syms[r.sym-1].Value
		}
	}
	if off != sym.Value {
		problems = append(problems, fmt.Sprintf("global %s: the DATASEC offset is %d (raw %d + .rel.BTF; the ELF symbol is at %d)", g.Name, off, vsi.offset, sym.Value))
	}
	if uint64(vsi.size) != sym.Size {
		problems = append(problems, fmt.Sprintf("global %s: the DATASEC size is %d (the ELF symbol has %d)", g.Name, vsi.size, sym.Size))
	}
	if sec != nil && uint64(vsi.offset)+uint64(vsi.size) > sec.Size {
		problems = append(problems, fmt.Sprintf("global %s: the DATASEC range [%d, %d) exceeds the ELF section size %d", g.Name, vsi.offset, vsi.offset+vsi.size, sec.Size))
	}
	vt := b.resolve(b.types[vsi.typeID].typeID)
	if vt.kind != kindInt {
		problems = append(problems, fmt.Sprintf("global %s: the VAR type (kind %d) is not INT", g.Name, vt.kind))
	} else {
		if vt.size != g.Size {
			problems = append(problems, fmt.Sprintf("global %s: the VAR type %s has size %d (declared %d)", g.Name, vt.name, vt.size, g.Size))
		}
		if vt.signed != g.Signed {
			problems = append(problems, fmt.Sprintf("global %s: the VAR type %s has signed=%v (declared %v)", g.Name, vt.name, vt.signed, g.Signed))
		}
	}
	return problems
}

// resolve unwraps typedef/const/volatile and other qualifiers.
func (b *btf) resolve(id uint32) *btfType {
	for i := 0; i < 32 && int(id) < len(b.types); i++ {
		t := b.types[id]
		switch t.kind {
		case kindTypedef, kindVolatile, kindConst, kindRestrict, kindTypeTag:
			id = t.typeID
		default:
			return t
		}
	}
	return &btfType{}
}

func (b *btf) sizeOf(id uint32) uint32 { return b.sizeOfDepth(id, 0) }

// btfMaxDepth bounds ARRAY recursion at 64, matching the C loader and
// preventing stack overflow on cyclic BTF.
const btfMaxDepth = 64

func (b *btf) sizeOfDepth(id uint32, d int) uint32 {
	if d > btfMaxDepth {
		return 0
	}
	t := b.resolve(id)
	switch t.kind {
	case kindPtr:
		return 8
	case kindArray:
		return b.sizeOfDepth(t.typeID, d+1) * t.nelems
	}
	return t.size
}

// MapSymbols returns sorted .maps symbols, the canonical names cilium uses
// to assign generated Objects maps. Missing .maps returns an empty list.
func MapSymbols(elfBytes []byte) ([]string, error) {
	f, err := elf.NewFile(bytes.NewReader(elfBytes))
	if err != nil {
		return nil, fmt.Errorf("cannot read ELF: %w", err)
	}
	idx := -1
	for i, s := range f.Sections {
		if s.Name == ".maps" {
			idx = i
			break
		}
	}
	if idx < 0 {
		return nil, nil
	}
	syms, err := f.Symbols()
	if err != nil {
		return nil, fmt.Errorf("cannot read ELF symbols: %w", err)
	}
	seen := map[string]bool{}
	var names []string
	for _, s := range syms {
		if int(s.Section) != idx || s.Name == "" || elf.ST_TYPE(s.Info) == elf.STT_SECTION || seen[s.Name] {
			continue
		}
		seen[s.Name] = true
		names = append(names, s.Name)
	}
	sort.Strings(names)
	return names, nil
}

// Member is a language-independent BTF STRUCT member. Type uses specification
// section 3 spellings: u8..i64, [N]T, record:<T>, bpf_spin_lock or bpf_timer,
// matching maps.json records in docs/requirements_format.md section 12.
// Unrepresentable union/pointer/bitfield types use ?<reason>. BTF lacks endianness.
type Member struct {
	Name   string `json:"name"`
	Offset uint32 `json:"offset"`
	Type   string `json:"type"`
}

// RecordShape contains size and members sorted by offset.
type RecordShape struct {
	Size    uint32   `json:"size"`
	Members []Member `json:"members"`
}

// String formats diagnostics as size=24;a:0:u8;arr:4:[4]u32;.
func (r RecordShape) String() string {
	var b strings.Builder
	fmt.Fprintf(&b, "size=%d;", r.Size)
	for _, m := range r.Members {
		fmt.Fprintf(&b, "%s:%d:%s;", m.Name, m.Offset, m.Type)
	}
	return b.String()
}

// ErrNoRecord means the ELF BTF lacks the named STRUCT.
var ErrNoRecord = fmt.Errorf("the ELF BTF has no such struct")

// BTFRecords reads BTF once and returns a named-STRUCT lookup. Duplicate names
// are errors in parseBTF.
func BTFRecords(elfBytes []byte) (func(name string) (RecordShape, error), error) {
	b, err := parseBTF(elfBytes)
	if err != nil {
		return nil, err
	}
	return func(name string) (RecordShape, error) {
		id, ok := b.structs[name]
		if !ok {
			return RecordShape{}, ErrNoRecord
		}
		t := b.types[id]
		r := RecordShape{Size: t.size}
		for _, m := range t.members {
			ty := b.spell(m.typeID)
			if t.bitfield {
				ty = "?bitfield"
			}
			r.Members = append(r.Members, Member{m.name, m.offset, ty})
		}
		sort.SliceStable(r.Members, func(i, j int) bool { return r.Members[i].Offset < r.Members[j].Offset })
		return r, nil
	}, nil
}

// spell converts a BTF type to specification section 3 spelling.
func (b *btf) spell(id uint32) string { return b.spellDepth(id, 0) }

func (b *btf) spellDepth(id uint32, d int) string {
	if d > btfMaxDepth {
		return "?too_deep"
	}
	t := b.resolve(id)
	switch t.kind {
	case kindInt:
		s := "u"
		if t.signed {
			s = "i"
		}
		return fmt.Sprintf("%s%d", s, t.size*8)
	case kindArray:
		return fmt.Sprintf("[%d]%s", t.nelems, b.spellDepth(t.typeID, d+1))
	case kindStruct:
		switch t.name {
		case "":
			return "?anonymous_struct"
		case "bpf_spin_lock", "bpf_timer":
			return t.name
		}
		return "record:" + t.name
	case kindUnion:
		return "?union"
	case kindPtr:
		// Record spelling requires a named target. Do not change kptrTarget's
		// opaque-hole recognition of a direct PTR -> TYPE_TAG kptr.
		if name, ok := b.kptrTarget(id); ok && name != "" {
			return "kptr:" + name
		}
		return "?pointer"
	case kindEnum, kindEnum64:
		return "?enum"
	}
	return fmt.Sprintf("?btf_kind_%d", t.kind)
}
